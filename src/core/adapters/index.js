// Agent adapters. Each adapter describes what an environment really
// supports. "compatibility" uses four levels:
//
//   native      the agent reads Agent Skills folders (SKILL.md) directly
//   adapter     the hub converts the skill into the agent's own format
//   manual      no local folder: the hub prepares a file the user imports by hand
//   unverified  documented by the vendor but not verified by this project
//
// A new adapter can be added in two ways without touching the core:
//   1. a declarative JSON file in <dataDir>/adapters/ (no code is executed)
//   2. a JavaScript module registered with registerAdapter() (developers)

import os from 'node:os';
import path from 'node:path';
import fsp from 'node:fs/promises';
import { exists, ensureDir, copyDir, safeSlug, readJson } from '../fsutil.js';
import { splitFrontmatter } from '../skill-parser.js';

const HOME = os.homedir();
const expand = (p) => (p.startsWith('~') ? path.join(HOME, p.slice(1)) : p);

async function pathState(p) {
  try {
    const st = await fsp.lstat(p);
    if (st.isSymbolicLink()) {
      try {
        await fsp.stat(p);
        return 'ok';
      } catch {
        return 'broken-link';
      }
    }
    return st.isDirectory() ? 'ok' : 'not-a-directory';
  } catch {
    return 'missing';
  }
}

/** Base for agents that read Agent Skills folders. */
function skillFolderAdapter(def) {
  return {
    layout: 'skill-folder',
    formats: ['SKILL.md', 'Agent Skills folder', 'scripts', 'references', 'assets'],
    capabilities: { detect: true, import: true, export: true, install: true, sync: true },
    ...def,
    async locations(projectDir) {
      const list = [];
      for (const p of def.userPaths || []) list.push({ scope: 'user', path: expand(p) });
      if (projectDir) for (const p of def.projectPaths || []) list.push({ scope: 'project', path: path.join(projectDir, p) });
      for (const l of list) l.state = await pathState(l.path);
      return list;
    },
    async detect() {
      const evidence = [];
      for (const p of def.detectPaths || []) {
        const full = expand(p);
        if (await exists(full)) evidence.push(full);
      }
      return { installed: evidence.length > 0, evidence };
    },
    targetPath(root, skill) {
      return path.join(root, skill.slug || safeSlug(skill.name));
    },
    /** Copies the skill folder as is. Returns the written path. */
    async install(skillDir, root, skill) {
      const target = this.targetPath(root, skill);
      await ensureDir(target);
      await copyDir(skillDir, target);
      return target;
    }
  };
}

/** Converts SKILL.md into a Cursor rule (.mdc). Extra files are not carried. */
const cursor = {
  id: 'cursor',
  label: 'Cursor',
  vendor: 'Anysphere',
  compatibility: 'adapter',
  layout: 'single-file',
  formats: ['.cursor/rules/*.mdc'],
  capabilities: { detect: true, import: true, export: true, install: true, sync: true },
  userPaths: [],
  projectPaths: ['.cursor/rules'],
  detectPaths: ['~/.cursor', '~/AppData/Roaming/Cursor', '~/Library/Application Support/Cursor', '~/.config/Cursor'],
  limits: [
    'Seul le contenu de SKILL.md est converti en règle .mdc ; les scripts et ressources ne sont pas copiés.',
    'Les règles Cursor sont liées à un projet (.cursor/rules) ; il n\'y a pas de dossier global géré par fichiers.',
    'La prise en charge native des Agent Skills par Cursor n\'est pas vérifiée par ce projet.'
  ],
  notes: 'Format de règle Cursor : frontmatter description, globs, alwaysApply.',
  async locations(projectDir) {
    if (!projectDir) return [];
    const p = path.join(projectDir, '.cursor', 'rules');
    return [{ scope: 'project', path: p, state: await pathState(p) }];
  },
  async detect() {
    const evidence = [];
    for (const p of this.detectPaths) if (await exists(expand(p))) evidence.push(expand(p));
    return { installed: evidence.length > 0, evidence };
  },
  targetPath(root, skill) {
    return path.join(root, `${skill.slug || safeSlug(skill.name)}.mdc`);
  },
  convert(skillMdText, skill) {
    const { body } = splitFrontmatter(skillMdText);
    const desc = String(skill.description || '').replace(/\r?\n/g, ' ').replace(/"/g, '\\"');
    return `---\ndescription: "${desc}"\nglobs:\nalwaysApply: false\n---\n<!-- Generated by Universal Skills Hub from skill "${skill.name}". Edit the source skill, not this file. -->\n${body.replace(/^\s+/, '')}`;
  },
  async install(skillDir, root, skill) {
    const text = await fsp.readFile(path.join(skillDir, 'SKILL.md'), 'utf8');
    const target = this.targetPath(root, skill);
    await ensureDir(root);
    await fsp.writeFile(target, this.convert(text, skill));
    return target;
  }
};

/** Manual adapters: the hub writes an export the user uploads or pastes. */
function manualAdapter(def) {
  return {
    layout: 'manual',
    capabilities: { detect: false, import: true, export: true, install: false, sync: false },
    userPaths: [],
    projectPaths: [],
    ...def,
    async locations() {
      return [];
    },
    async detect() {
      const evidence = [];
      for (const p of def.detectPaths || []) if (await exists(expand(p))) evidence.push(expand(p));
      return { installed: evidence.length > 0, evidence };
    }
  };
}

