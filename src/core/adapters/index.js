const registry = new Map(BUILTIN.map((a) => [a.id, a]));

export function registerAdapter(adapter) {
  if (!adapter?.id || !adapter.label) throw new Error('Un adaptateur doit avoir un id et un label.');
  registry.set(adapter.id, adapter);
  return adapter;
}

export function getAdapter(id) {
  return registry.get(id) || null;
}

export function listAdapters() {
  return [...registry.values()];
}

/** Loads declarative adapters from <dataDir>/adapters/*.json. No code is executed. */
export async function loadCustomAdapters(dataDir) {
  const dir = path.join(dataDir, 'adapters');
  const loaded = [];
  const errors = [];
  let files = [];
  try {
    files = (await fsp.readdir(dir)).filter((f) => f.endsWith('.json'));
  } catch {
    return { loaded, errors };
  }
  for (const f of files) {
    try {
      const def = await readJson(path.join(dir, f));
      if (!/^[a-z0-9-]{2,40}$/.test(def.id || '')) throw new Error('id invalide (a-z, 0-9, tiret)');
      if (registry.has(def.id) && !registry.get(def.id).custom) throw new Error('id déjà utilisé par un adaptateur intégré');
      const a = skillFolderAdapter({
        id: def.id,
        label: String(def.label || def.id),
        vendor: String(def.vendor || 'Personnalisé'),
        compatibility: ['native', 'unverified'].includes(def.compatibility) ? def.compatibility : 'unverified',
        userPaths: (def.userPaths || []).map(String),
        projectPaths: (def.projectPaths || []).map(String),
        detectPaths: (def.detectPaths || []).map(String),
        limits: (def.limits || []).map(String),
        notes: String(def.notes || 'Adaptateur déclaratif personnalisé.'),
        custom: true
      });
      registry.set(a.id, a);
      loaded.push(a.id);
    } catch (err) {
      errors.push({ file: f, error: err.message });
    }
  }
  return { loaded, errors };
}

/** Summary used by the UI and by COMPATIBILITY.md. */
export function describeAdapter(a) {
  return {
    id: a.id,
    label: a.label,
    vendor: a.vendor,
    compatibility: a.compatibility,
    layout: a.layout,
    formats: a.formats,
    capabilities: a.capabilities,
    userPaths: (a.userPaths || []).map(expand),
    projectPaths: a.projectPaths || [],
    limits: a.limits || [],
    notes: a.notes || '',
    custom: !!a.custom,
    exportFormat: a.exportFormat || null
  };
}
